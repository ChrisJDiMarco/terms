import { _electron as electron, expect } from '@playwright/test';
import { mkdtemp, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { createGame, applyMove, scores } from '../src/game.js';

const root = path.resolve(import.meta.dirname, '..');
const testData = await mkdtemp(path.join(tmpdir(), 'terms-e2e-'));
const executablePath = process.env.TERMS_EXECUTABLE;
const launch = () => electron.launch({ ...(executablePath ? { executablePath, args: [] } : { args: [root] }), env: { ...process.env, TERMS_TEST_DATA: testData } });
let desktop = await launch();
let page = await desktop.firstWindow();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await expect(page.locator('#instruction')).toHaveText('What will you keep?');
await expect(page.locator('#table canvas')).toBeVisible();
await page.locator('#mode').click();
await page.locator('#start-local').click();
await expect(page.locator('#turn-label')).toContainText('PLAYER TWO');
await page.keyboard.press('1');
await expect(page.locator('#keep-choice')).toHaveText('Red');
await expect(page.locator('#commit')).toBeDisabled();
await page.keyboard.press('1');
await expect(page.locator('#give-choice')).toHaveText('Red');
await expect(page.locator('#remaining-0')).toHaveText('5');
await expect(page.locator('#commit')).toBeEnabled();
await page.locator('#clear').click();
await expect(page.locator('#remaining-0')).toHaveText('7');
await page.locator('[data-color="0"]').click();
await page.locator('[data-color="1"]').click();
await page.locator('#commit').click();
await expect(page.locator('#turn-label')).toContainText('PLAYER ONE');
await expect(page.locator('#last-move')).toContainText('Player Two kept Red');
await page.locator('#rules').click();
await expect(page.locator('#dialog')).toBeVisible();
await page.locator('#motion-setting').check();
await page.keyboard.press('Escape');
await expect(page.locator('#dialog')).not.toBeVisible();
await page.locator('#top').click();
await expect(page.locator('#top')).toHaveAttribute('aria-pressed', 'true');
await page.screenshot({ path: path.join(root, 'evidence/e2e-top.png') });
await page.locator('#perspective').click();
const canvas = await page.locator('#table canvas').boundingBox();
await page.mouse.move(canvas.x + canvas.width * .5, canvas.y + canvas.height * .5);
await page.mouse.down();
await page.mouse.move(canvas.x + canvas.width * .6, canvas.y + canvas.height * .57, { steps: 10 });
await page.mouse.up();
await expect(page.locator('#keep-choice')).toHaveText('Choose a counter');
await page.mouse.wheel(0, -120);
await page.screenshot({ path: path.join(root, 'evidence/e2e-orbit.png') });
await page.locator('#reset-view').click();

const history = [[1,2],[2,2],[0,2],[0,2],[0,2],[3,3],[2,3],[3,0],[0,3],[1,0]];
let endgame = createGame();
for (const [keep,give] of history) endgame = applyMove(endgame, {keep,give});
await page.evaluate(async game => window.termsStore.save({version:1,game,sound:false,reducedMotion:true}), endgame);
await page.reload();
await expect(page.locator('#player-0 .score-line>strong')).toHaveText('8');
await expect(page.locator('#player-1 .score-line>strong')).toHaveText('7');
await page.locator('[data-color="0"]').click();
await expect(page.locator('[data-color="0"]')).toBeDisabled();
await page.locator('#clear').click();
for (const [keep,give] of [[3,3],[0,1],[1,1],[1,1]]) {
  await page.locator(`[data-color="${keep}"]`).click();
  await page.locator(`[data-color="${give}"]`).click();
  await page.locator('#commit').click();
}
await expect(page.locator('#finished')).toBeVisible();
await expect(page.locator('#outcome')).toHaveText('Player One wins.');
await expect(page.locator('#player-0 .score-line>strong')).toHaveText('13');
await expect(page.locator('#player-1 .score-line>strong')).toHaveText('11');
await page.screenshot({ path: path.join(root, 'evidence/e2e-complete.png') });
await desktop.close();
const saved = JSON.parse(await readFile(path.join(testData, 'table.json'), 'utf8'));
expect(saved.game.moveCount).toBe(14);
expect(scores(saved.game)).toEqual([13,11]);
desktop = await launch(); page = await desktop.firstWindow();
page.on('pageerror', error => errors.push(error.message));
await expect(page.locator('#finished')).toBeVisible();
await page.locator('#rematch').click();
await expect(page.locator('#turn-label')).toContainText('PLAYER TWO');
await expect(page.locator('#remaining-0')).toHaveText('7');
await page.locator('#mode').click();
await page.locator('#start-computer').click();
let moves = 0;
while (moves < 7) {
  await expect(page.locator('#turn-label')).toHaveText('YOUR TURN');
  await page.locator('.color-choice:enabled').first().click();
  await page.locator('.color-choice:enabled').first().click();
  await page.locator('#commit').click();
  moves++;
  if (moves < 7) await expect(page.locator('#turn-label')).toHaveText('YOUR TURN');
}
await expect(page.locator('#finished')).toBeVisible();
await page.screenshot({ path: path.join(root, 'evidence/e2e-computer-complete.png') });
expect(errors).toEqual([]);
await desktop.close();
console.log(JSON.stringify({result:'PASS',testData,checks:['local turns','keyboard','same-color','clear','legality','rules','reduced motion','view','drag does not select','zoom','worked ending 13–11','quit save','restore','rematch starter','complete computer game','no renderer errors']}));
